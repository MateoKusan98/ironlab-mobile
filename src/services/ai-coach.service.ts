import { api } from './api';

import { FormValues } from '@shared';
// LLM session generation runs a reasoning model server-side and routinely takes
// far longer than the api client's default 15s timeout — without this override
// the mobile client aborts with a timeout error while the backend completes and
// saves the plan (the user then sees an error on a session that did generate).
const PLAN_GEN_TIMEOUT_MS = 120000;

export interface NextSessionExercise {
  name: string;
  sets: number;
  reps: number;
  weight: number;
  rpe?: number;
  weightPerc?: number;
  cue?: string;
}

/** Schedule + big-3 frequency the coach infers from recent logged sessions. */
export interface SuggestedConstraints {
  trainingDays: string[] | null;
  sessionsPerWeek: number | null;
  avgSessionMinutes: number | null;
  squatFrequencyPerWeek: number | null;
  benchFrequencyPerWeek: number | null;
  deadliftFrequencyPerWeek: number | null;
  sessionCount: number;
}

export interface NextSession {
  focus: string;
  exercises: NextSessionExercise[];
  /** 3-sentence coach rationale: key insight, why this load/focus, what to watch. */
  coachsCall?: string;
}

export interface ChatMessage {
  role: 'user' | 'assistant';
  content: string;
}

export interface CoachPreferences {
  timeSlot: 'morning' | 'afternoon' | 'evening';
  duration: number;
  intensity: number;
}

export type FatigueLevel = 'none' | 'mild' | 'elevated' | 'high';

export interface FatigueStatus {
  requiresAck: boolean;
  level: FatigueLevel;
  reasons: string[];
  /** True while an "I feel fine" dismissal is live (until the next logged session). */
  dismissed: boolean;
  /** The athlete may clear this alarm (elevated/high, not dismissed, not a scheduled deload). */
  canDismiss: boolean;
  /** This is a programmed deload week — planned recovery, not a reactive flag. */
  scheduledDeload: boolean;
  /** What the coach wants done about it — 'taper' when a max attempt is close enough
   *  that a deload would clear the fatigue but leave the athlete flat for it. */
  recommendation: FatigueRecommendation | null;
}

export interface FatigueRecommendation {
  action: 'taper' | 'deload' | 'trim';
  peak: { kind: 'competition' | 'pr_test' | 'block_peak'; daysAway: number | null; label: string } | null;
  headline: string;
  detail: string;
}

/** Mirrors backend pr-forecast.ts. See that module for what each verdict promises. */
export type PrVerdict = 'primed' | 'on_track' | 'hold' | 'not_today' | 'deferred' | 'insufficient_data';

export interface PrDriver {
  key: string;
  direction: 'positive' | 'negative' | 'neutral';
  detail: string;
}

export interface PrLiftForecast {
  lift: 'squat' | 'bench' | 'deadlift';
  label: string;
  verdict: PrVerdict;
  /** Best logged single — the number a true PR has to beat. */
  record: number | null;
  /** What the current block's sets project a top single at. */
  projectedTop: number | null;
  marginPct: number | null;
  /** The cheaper record: a triple that would also stand. */
  triple: { record: number | null; projected: number | null } | null;
  confidence: 'high' | 'medium' | 'low';
  drivers: PrDriver[];
  headline: string;
  detail: string;
  /** ISO date a deferred attempt lands on (taper windows only). */
  attemptWindow: string | null;
  /** Whether a single or triple is actually programmed — only those can set a record. */
  attemptScheduled: boolean;
  sessionsInBlock: number;
}

export interface PrForecast {
  lifts: PrLiftForecast[];
  /** The lift closest to a record — what the single-card UI shows. */
  best: PrLiftForecast | null;
  /** Set when the feature is deliberately silent (hypertrophy athletes never max). */
  suppressed: 'hypertrophy' | null;
  generatedAt: string;
}

export interface CoachNote {
  id: string;
  category: string;
  description: string;
  exerciseName: string | null;
  autoGenerated: boolean;
  createdAt: string;
}

export type PathTier = 'novice' | 'beginner' | 'intermediate' | 'advanced';
export type PathBranchId = 'muscle' | 'powerbuilding' | 'strength';
export type PathNodeState = 'completed' | 'current' | 'available' | 'locked';

export interface PathTierNode {
  tier: PathTier;
  label: string;
  state: PathNodeState;
}

export interface PathBranch {
  id: PathBranchId;
  label: string;
  icon: string;
  isCurrent: boolean;
  tiers: PathTierNode[];
}

export interface PathMilestone {
  id: string;
  label: string;
  description: string;
  icon: string;
  kind: 'consistency' | 'strength';
  achieved: boolean;
  progress: number;
  current: number;
  target: number;
  unit: string;
}

export interface PathTree {
  currentBranchId: PathBranchId;
  currentTier: PathTier;
  foundation: PathNodeState;
  branches: PathBranch[];
  milestones: PathMilestone[];
  nextMilestones: PathMilestone[];
}

