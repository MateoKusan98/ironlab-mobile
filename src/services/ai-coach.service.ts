export interface AdminUserEntry {
  id: string;
  email: string;
  name: string;
  role: string;
  hasAIProfile: boolean;
  totalSessions: number;
}

export interface AdminUserState {
  userId: string;
  phase: string | null;
  weekInPhase: number;
  totalWeeks: number;
  phaseStartedAt: string | null;
  extensionWeeks: number;
  cycleSlot: number;
  totalSessions: number;
  testCycleSlotOffset: number;
  fatigueOverride: string | null;
  fatigueReal: string;
  fatigueEvidence: string[];
  /** Exactly what GET /ai-coach/fatigue-check returns for this user — i.e. the level
   *  the athlete is shown on the plan banner + readiness gate, override applied. */
  fatigueAthlete: {
    level: string;
    dismissed: boolean;
    scheduledDeload: boolean;
    requiresAck: boolean;
    reasons: string[];
  };
  /** Exactly what GET /ai-coach/pr-forecast returns for this user. */
  prForecast: PrForecast;
  /** How often past forecasts matched what the bar did. */
  prForecastAccuracy: {
    tested: number;
    correct: number;
    accuracyPct: number | null;
    open: number;
    unattempted: number;
  };
  memoryLength: number;
  memoryArchiveLength: number;
  activeNotesCount: number;
  exerciseIntelCount: number;
  planRateLimitCount: number;
  planRateLimitMax: number;
  trainingDays: string[] | null;
  squatFreq: number | null;
  benchFreq: number | null;
  deadliftFreq: number | null;
  nextSessionJson: NextSession | null;
  planGeneratedAt: string | null;
}

