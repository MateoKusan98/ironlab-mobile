/** Returns a new array of the questions shuffled (Fisher–Yates). */
export function shuffleQuestions(questions: QuizQuestion[] = FITNESS_QUIZ): QuizQuestion[] {
  const arr = [...questions];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
