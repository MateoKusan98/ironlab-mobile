// Fitness quiz bank — used both as a standalone "learn" quiz in the profile and
// as something fun to do while long AI calls (plan generation, food analysis) run.
// English-only for now; localisation is a future step (see LANGUAGES in i18n).
//
// Writing rules for questions (keep the quiz un-gameable):
//  - Every distractor must be plausible — something a person could genuinely
//    believe. Never joke answers, never absurd options.
//  - All options in a question should be similar in length and tone, so the
//    longest/most-detailed option is NOT a tell for the correct one.
//  - Option order is shuffled at runtime (see buildDeck), so position never
//    encodes the answer — but still vary `correct` in the source data.
//  - Each question has a difficulty; the quiz adapts or filters on it.

