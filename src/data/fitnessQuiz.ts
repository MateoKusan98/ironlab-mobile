/** Fisher–Yates shuffle (returns a new array). */
function shuffle<T>(arr: T[]): T[] {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** Shuffles a question's answer options, remapping `correct`. */
function shuffleOptions(q: QuizQuestion): QuizQuestion {
  const order = shuffle(q.options.map((_, i) => i));
  return {
    ...q,
    options: order.map((i) => q.options[i]),
    correct: order.indexOf(q.correct),
  };
}

/**
 * Builds a shuffled deck for one difficulty level. Also shuffles each
 * question's answer options (remapping `correct`), so neither the position
 * nor the source order of an option ever hints at the answer.
 */
export function buildDeck(difficulty?: QuizDifficulty): QuizQuestion[] {
  const pool = difficulty ? FITNESS_QUIZ.filter((q) => q.difficulty === difficulty) : FITNESS_QUIZ;
  return shuffle(pool).map(shuffleOptions);
}

// ─── Chess-style quiz rating (Elo) ───────────────────────────
//
// The player carries a persistent rating; each question has a rating from its
// difficulty tier. Answering is a "game" against the question: beating a
// question far above you pays a lot, missing one far below you costs a lot,
// and mismatched pairings barely move the needle — exactly like chess.

export const DEFAULT_QUIZ_RATING = 1000;
export const QUIZ_RATING_MIN = 400;
export const QUIZ_RATING_MAX = 2400;
export const QUIZ_RATING_STORAGE_KEY = '@ironlab/fitness_quiz_rating';

/** Elo rating of a question by difficulty tier. */
export const QUESTION_RATING: Record<QuizDifficulty, number> = {
  1: 1000,
  2: 1400,
  3: 1800,
};

/**
 * Rating thresholds that unlock knowledge badges (mirrors the backend's
 * QUIZ_RATING_BADGES and the QUIZ_RATING_* BadgeKeys). Crossing one upward
 * should be reported via badgesService.recordQuizRating.
 */
export const QUIZ_RATING_MILESTONES = [1100, 1400, 1700, 2000, 2200] as const;

/** Chess-style titles for rating bands. */
export function ratingTitle(rating: number): string {
  if (rating < 800) return 'Rookie';
  if (rating < 1100) return 'Novice';
  if (rating < 1400) return 'Enthusiast';
  if (rating < 1700) return 'Athlete';
  if (rating < 2000) return 'Coach';
  if (rating < 2200) return 'Expert';
  return 'Master';
}

/**
 * Elo rating change for one answered question.
 * K = 32 gives lively but stable swings for a quiz cadence.
 */
export function eloDelta(playerRating: number, questionRating: number, correct: boolean, k = 32): number {
  const expected = 1 / (1 + Math.pow(10, (questionRating - playerRating) / 400));
  const delta = Math.round(k * ((correct ? 1 : 0) - expected));
  // A correct answer never reads as a loss (rounding can hit 0 — allow that
  // only for hugely mismatched pairings, mirroring chess's "no reward" games).
  return delta;
}

/** Clamps a rating into the supported band. */
export function clampRating(rating: number): number {
  return Math.min(QUIZ_RATING_MAX, Math.max(QUIZ_RATING_MIN, Math.round(rating)));
}

/**
 * Draws the next rated question: picks a difficulty tier with probability
 * weighted by closeness to the player's rating (mostly at-level questions,
 * some stretch either way), then a random question from that tier that
 * hasn't been seen recently. Options come pre-shuffled.
 */
export function drawRatedQuestion(playerRating: number, recentIds: number[] = []): QuizQuestion {
  const tiers: QuizDifficulty[] = [1, 2, 3];
  const sigma = 300;
  const weights = tiers.map((t) => Math.exp(-((playerRating - QUESTION_RATING[t]) ** 2) / (2 * sigma * sigma)));
  const total = weights.reduce((a, b) => a + b, 0);

  let roll = Math.random() * total;
  let tier: QuizDifficulty = 1;
  for (let i = 0; i < tiers.length; i++) {
    roll -= weights[i];
    if (roll <= 0) {
      tier = tiers[i];
      break;
    }
    tier = tiers[i];
  }

  const inTier = FITNESS_QUIZ.filter((q) => q.difficulty === tier);
  const fresh = inTier.filter((q) => !recentIds.includes(q.id));
  const pool = fresh.length > 0 ? fresh : inTier;
  return shuffleOptions(pool[Math.floor(Math.random() * pool.length)]);
}
